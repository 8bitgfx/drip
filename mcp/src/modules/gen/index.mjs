// Image generation with any provider: built-ins (OpenAI, Gemini) + your own adapters in ~/.drip/providers/.
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { z } from "zod";
import { fetchImage, imageBlock, toJpeg } from "../../core/images.mjs";
import { getKey, keyStatus, logUsage } from "../../core/keys.mjs";
import { homeDripDir, projectDir, projectDripDir, ensureDir } from "../../core/paths.mjs";
import { blocks, safe, text } from "../../core/result.mjs";
import gemini from "./providers/gemini.mjs";
import openai from "./providers/openai.mjs";
import { openKeyPage } from "./keypage.mjs";

const BUILT_IN = [openai, gemini];

async function providers() {
  const list = [...BUILT_IN];
  const dir = path.join(homeDripDir, "providers");
  if (fs.existsSync(dir))
    for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".mjs"))) {
      try {
        const mod = await import(pathToFileURL(path.join(dir, f)).href);
        if (mod.default?.id && mod.default?.generate) list.push(mod.default);
      } catch {
        /* a broken custom provider must not take the server down */
      }
    }
  return list;
}

const KEY_NAMES = ["openai", "gemini", "unsplash", "pexels", "openverse"];

export function register(server, ctx) {
  server.registerTool(
    "gen_image",
    {
      title: "Generate an image",
      description:
        "Generate hero art, illustrations, textures or product renders with the user's own provider key (OpenAI or Gemini built in; custom providers in ~/.drip/providers). " +
        "Saves into the project and shows you the result. Art-direct the prompt from the chosen direction (read drip_guide imagery/prompting): subject, composition, light, palette, negative space for text. " +
        "If no key is set, call keys_open and ask the user to paste one, or ask them for their own assets. Costs money: generate one, look, then iterate.",
      inputSchema: {
        prompt: z.string(),
        out: z.string().describe("Project path to save, e.g. public/images/hero.png"),
        aspect: z.enum(["landscape", "portrait", "square"]).optional(),
        provider: z.string().optional(),
        model: z.string().optional(),
        refs: z.array(z.string()).optional().describe("Reference image URLs for style (providers that support it)"),
      },
    },
    safe(async ({ prompt, out, aspect = "landscape", provider, model, refs = [] }) => {
      const config = ctx.config();
      const all = await providers();
      const id = provider || config.gen.defaultProvider;
      const p = all.find((x) => x.id === id) || all.find((x) => getKey(x.key));
      if (!p) return text(`Unknown provider "${id}". Available: ${all.map((x) => x.id).join(", ")}`, true);
      const key = getKey(p.key);
      if (!key) {
        const url = await openKeyPage([...new Set([...KEY_NAMES, ...all.map((x) => x.key)])]);
        return text(`No key for ${p.label}. Ask the user to open ${url} and paste a key (it stays on their machine), or to provide their own image. Then try again.`, true);
      }
      const refImgs = await Promise.all(refs.map((u) => fetchImage(u)));
      const imgs = await p.generate({ prompt, aspect, model: model || config.gen.providers?.[p.id]?.model, refs: refImgs }, key);
      const file = path.resolve(projectDir(), out);
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, imgs[0].buf);
      logUsage({ kind: "gen_image", provider: p.id, model: model || config.gen.providers?.[p.id]?.model, out, prompt: prompt.slice(0, 300) });
      const log = path.join(ensureDir(projectDripDir()), "assets.json");
      const list = fs.existsSync(log) ? JSON.parse(fs.readFileSync(log, "utf8")) : [];
      list.push({ file: out, source: `generated by ${p.label}`, prompt, license: "generated (check provider terms)", savedAt: new Date().toISOString() });
      fs.writeFileSync(log, JSON.stringify(list, null, 2));
      return blocks([{ type: "text", text: `Saved ${out} via ${p.label}. Judge it against the direction; if it misses, change one thing in the prompt and regenerate.` }, imageBlock(await toJpeg(imgs[0].buf, 1400, 1400))]);
    }),
  );

  server.registerTool(
    "gen_providers",
    { title: "Image providers", description: "Lists image providers (built-in and custom) and whether each has a key. To add a new provider, copy mcp/src/modules/gen/providers/_template.mjs.txt to ~/.drip/providers/<id>.mjs.", inputSchema: {} },
    safe(async () => {
      const all = await providers();
      return text(all.map((p) => `- ${p.id}: ${p.label} — key ${getKey(p.key) ? "set" : "missing"}`).join("\n") + "\n\nAdd a key: keys_open. Add a provider: ~/.drip/providers/<id>.mjs (template in the Drip repo).");
    }),
  );

  server.registerTool(
    "keys_status",
    { title: "Which API keys are set", description: "Shows which optional keys (image generation, photo sources) are set and where from. Never shows values.", inputSchema: {} },
    safe(async () => text(keyStatus(KEY_NAMES).map((k) => `- ${k.name}: ${k.set ? `set (${k.from})` : "not set"}`).join("\n"))),
  );

  server.registerTool(
    "keys_open",
    { title: "Let the user paste API keys", description: "Opens a local page (link valid 30 minutes) where the USER pastes API keys. Give them the link; never ask them to paste keys into the chat.", inputSchema: {} },
    safe(async () => {
      const all = await providers();
      const url = await openKeyPage([...new Set([...KEY_NAMES, ...all.map((x) => x.key)])]);
      return text(`Give the user this link to paste keys (stays on their machine): ${url}`);
    }),
  );
}
