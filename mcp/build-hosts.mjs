// Generates hosts/<host>/ (packaging templates) from the shared sources: skills/, agents/critic.md, the server bundle path, the rules.
//   node build-hosts.mjs            write hosts/ (committed; placeholders <DRIP_ROOT> and ${PLUGIN_ROOT} stand for the install location)
//   node build-hosts.mjs --check    fail if hosts/ is out of date (for CI)
//   node build-hosts.mjs --pack     also build self-contained packages in dist-hosts/ (ChatGPT/Codex plugin folders, drip.mcpb)
//   node build-hosts.mjs --mcpb     only the Claude Desktop extension: dist-hosts/drip.mcpb
// dist-hosts/ is not committed. It needs mcp/dist/drip-mcp.mjs (npm run build first).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { criticMarkdown, criticToml, hostRules } from "./src/hosts/adapt.mjs";
import { resolveOpts } from "./src/hosts/common.mjs";
import * as chatgptHost from "./src/hosts/chatgpt.mjs";
import * as claudeDesktop from "./src/hosts/claude-desktop.mjs";
import * as codex from "./src/hosts/codex.mjs";
import * as cursor from "./src/hosts/cursor.mjs";
import * as opencode from "./src/hosts/opencode.mjs";
import { copyRuntime, mcpbManifest, openaiPluginFiles, writeJsonFile } from "./src/hosts/packages.mjs";
import { zipDir } from "./src/hosts/zip.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const args = process.argv.slice(2);
const flag = (n) => args.includes(`--${n}`);

const DRIP_ROOT = "<DRIP_ROOT>";
const tpl = (extra = {}) => resolveOpts({ template: true, pluginRoot: DRIP_ROOT, home: "<HOME>", ...extra });

/** Everything under hosts/, as { relativePath: content }. */
export function renderTemplates() {
  const out = {};
  const json = (rel, data) => (out[rel] = `${JSON.stringify(data, null, 2)}\n`);
  const o = tpl();

  out["codex/config.toml"] = `# Add to ~/.codex/config.toml (drip install --agent codex does this and fills in <DRIP_ROOT>).\n${codex.tomlBlock(o)}\n`;
  json("codex/hooks.json", codex.hooksJson(o));
  out["codex/AGENTS.md"] = hostRules("codex", "full");
  out["codex/agents/drip-critic.toml"] = criticToml(root);

  json("cursor/mcp.json", { mcpServers: { drip: cursor.mcpEntry(o) } });
  json("cursor/hooks.json", cursor.hooksJson(o));
  out["cursor/rules/drip.mdc"] = cursor.ruleFile(hostRules("cursor", "full"));
  out["cursor/agents/drip-critic.md"] = criticMarkdown("cursor", root);

  json("opencode/opencode.json", { mcp: { drip: opencode.serverEntry(o) } });
  out["opencode/plugins/drip.js"] = opencode.pluginSource(o);
  out["opencode/agents/drip-critic.md"] = criticMarkdown("opencode", root);
  out["opencode/AGENTS.md"] = hostRules("opencode", "partial");

  json("claude-desktop/claude_desktop_config.json", { mcpServers: { drip: claudeDesktop.mcpEntry(o) } });
  json("claude-desktop/manifest.json", mcpbManifest(root));
  out["claude-desktop/AGENTS.md"] = hostRules("claude-desktop", "none");

  const plugin = openaiPluginFiles(tpl({ pluginRoot: "${PLUGIN_ROOT}" }), root);
  for (const [rel, data] of Object.entries(plugin)) json(`chatgpt/${rel}`, data);
  json("chatgpt/marketplace.json", { name: "local", plugins: [chatgptHost.marketplaceEntry("./.drip/hosts/chatgpt-plugin")] });

  out["README.md"] = `# Host packaging (generated)\n\nGenerated by \`cd mcp && npm run build:hosts\` from skills/, agents/critic.md and the host adapters in mcp/src/hosts. Do not edit by hand.\nThese are templates: \`<DRIP_ROOT>\` stands for the folder that holds this repository (or the installed plugin), \`\${PLUGIN_ROOT}\` and \`\${__dirname}\` are filled in by the host.\nTo install into a host: \`drip install --agent <codex|cursor|opencode|claude-desktop|chatgpt>\`. Details and the capability matrix: docs/HOSTS.md.\n`;
  return out;
}

/** The root plugin.json (Codex marketplace install) points at hooks/codex-plugin.json: generated too, so it never drifts. */
const PLUGIN_HOOKS = path.join(root, "hooks", "codex-plugin.json");
const pluginHooks = () => `${JSON.stringify(codex.hooksJson(tpl({ pluginRoot: "${PLUGIN_ROOT}" }), { plugin: true }), null, 2)}\n`;

function writeTemplates() {
  fs.writeFileSync(PLUGIN_HOOKS, pluginHooks());
  const files = renderTemplates();
  const dir = path.join(root, "hosts");
  fs.rmSync(dir, { recursive: true, force: true });
  for (const [rel, content] of Object.entries(files)) {
    const f = path.join(dir, rel);
    fs.mkdirSync(path.dirname(f), { recursive: true });
    fs.writeFileSync(f, content);
  }
  return Object.keys(files).length;
}

function checkTemplates() {
  const files = renderTemplates();
  const stale = [];
  if (!fs.existsSync(PLUGIN_HOOKS) || fs.readFileSync(PLUGIN_HOOKS, "utf8").replace(/\r\n/g, "\n") !== pluginHooks()) stale.push("../hooks/codex-plugin.json");
  for (const [rel, content] of Object.entries(files)) {
    const f = path.join(root, "hosts", rel);
    if (!fs.existsSync(f) || fs.readFileSync(f, "utf8").replace(/\r\n/g, "\n") !== content) stale.push(rel);
  }
  return stale;
}

export function packPlugin(host, dest) {
  const o = resolveOpts({ pluginRoot: root });
  copyRuntime(root, dest, host);
  for (const [rel, data] of Object.entries(openaiPluginFiles(o, root))) writeJsonFile(path.join(dest, rel), data);
  return dest;
}

export function packMcpb(outFile) {
  const stage = path.join(root, "dist-hosts", ".mcpb-stage");
  copyRuntime(root, stage, "claude-desktop");
  writeJsonFile(path.join(stage, "manifest.json"), mcpbManifest(root));
  const icon = path.join(root, ".claude-plugin", "icon.png");
  if (fs.existsSync(icon)) {
    fs.copyFileSync(icon, path.join(stage, "icon.png"));
    const m = JSON.parse(fs.readFileSync(path.join(stage, "manifest.json"), "utf8"));
    m.icon = "icon.png";
    writeJsonFile(path.join(stage, "manifest.json"), m);
  }
  const r = zipDir(stage, outFile);
  fs.rmSync(stage, { recursive: true, force: true });
  return r;
}

if (/build-hosts\.mjs$/.test(process.argv[1] || "")) {
  if (flag("check")) {
    const stale = checkTemplates();
    if (stale.length) {
      console.error(`hosts/ is out of date: ${stale.join(", ")}. Run: cd mcp && npm run build:hosts`);
      process.exit(1);
    }
    console.log("hosts/ is up to date.");
  } else if (flag("mcpb")) {
    const r = packMcpb(path.join(root, "dist-hosts", "drip.mcpb"));
    console.log(`dist-hosts/drip.mcpb: ${r.files} files, ${(r.bytes / 1048576).toFixed(1)} MB`);
  } else {
    console.log(`hosts/: ${writeTemplates()} files written`);
    if (flag("pack")) {
      for (const [host, name] of [["chatgpt", "chatgpt-plugin"], ["codex", "codex-plugin"]]) console.log(`dist-hosts/${name}: ${packPlugin(host, path.join(root, "dist-hosts", name))}`);
      const r = packMcpb(path.join(root, "dist-hosts", "drip.mcpb"));
      console.log(`dist-hosts/drip.mcpb: ${r.files} files, ${(r.bytes / 1048576).toFixed(1)} MB`);
    }
  }
}
